"""
Educational Q&A posts — five tracks, 10 a day each by default:

  dsa     Daily DSA: a problem, the approach, complexity, Python
  sd      System design: a scenario with numbers, components, trade-offs
  mlsd    ML system design: features, retrieval/ranking, evals, drift
  ai      AI engineering: agent loops/graphs, RAG, tool calling, evals, MCP
  papers  A real, recent paper (Hugging Face daily papers / arXiv) turned
          into "what changed, why it matters, where you'd use it"

Each item is a small JSON record (hook, question, answer, code, visual spec,
tags…). Items are generated by Azure OpenAI the night before (ensure_pool),
rendered to a designed card by `edu_cards`, and posted one per slot by
`post_one`. Three layers keep the posting guarantee intact:

  1. the day's pool (li_edu_pool.json) filled by the morning timers
  2. on-the-fly generation when the pool is empty at post time
  3. the hand-written seed bank (edu_seed.json) when the LLM is unavailable

The answer goes in the post body under LinkedIn's "…more" fold (the
comments API needs partner scopes we don't have) — which also makes people
comment their answer before expanding.
"""

