def _slug(s):
    return re.sub(r"[^a-z0-9]+", "-", (s or "").lower()).strip("-")[:60]


def _item_id(track, question):
    return track + "-" + hashlib.sha1(question.encode("utf-8")).hexdigest()[:10]


def validate(item, track):
    """Normalise + sanity-check a generated item. Returns the clean item or None."""
    if not isinstance(item, dict):
        return None
    q = str(item.get("question") or "").strip()
    a = str(item.get("answer") or "").strip()
    hook = str(item.get("hook") or "").strip().strip('"')
    if len(q) < 25 or len(a) < 60 or len(hook) < 10:
        return None
    vis = item.get("visual") if isinstance(item.get("visual"), dict) else {"kind": "none"}
    if vis.get("kind") not in VISUAL_KINDS:
        vis = {"kind": "none"}
    code = str(item.get("code") or "").strip()
    if code and len(code.splitlines()) > 18:
        code = "\n".join(code.splitlines()[:18])
    diff = str(item.get("difficulty") or "").lower()
    diff = diff if diff in ("easy", "medium", "hard") else None
    opts = item.get("options") if isinstance(item.get("options"), list) else []
    opts = [str(o).strip()[:80] for o in opts][:4]
    tags = [re.sub(r"[^A-Za-z0-9]", "", str(t)) for t in (item.get("tags") or []) if str(t).strip()][:3]
    allowed = COMPANY_POOLS.get(track, [])
    companies = []
    for c in (item.get("companies") or []):
        key = re.sub(r"[^a-z]", "", str(c).lower())
        if key in allowed and key not in companies:
            companies.append(key)
    companies = companies[:3]
    level = re.sub(r"\s+", " ", str(item.get("level") or "")).strip(" .")[:48]
    return {"id": _item_id(track, q), "track": track, "hook": hook[:120], "question": q[:420],
            "options": opts, "answer": a[:1400], "code": code, "complexity": str(item.get("complexity") or "")[:120],
            "takeaway": str(item.get("takeaway") or "")[:180], "difficulty": diff, "visual": vis,
            "tags": tags, "url": str(item.get("url") or "")[:300], "source": str(item.get("source") or "")[:80],
            "topic": str(item.get("topic") or "")[:80], "companies": companies, "level": level,
            "created": _now().isoformat()}


def seed_items(track):
    try:
        with open(SEED_FILE, encoding="utf-8") as f:
            bank = json.load(f)
    except Exception:
        return []
    out = []
    for raw in bank.get(track, []):
        it = validate(raw, track)
        if it:
            it["source"] = it["source"] or "seed"
            out.append(it)
    return out


# ---------- generation (LLM) ----------

def _parse_json(text):
    text = (text or "").strip()
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text, flags=re.S)
    try:
        return json.loads(text)
    except Exception:
        pass
    m = re.search(r"\{.*\}", text, flags=re.S)
    if m:
        try:
            return json.loads(m.group(0))
        except Exception:
            return None
    return None


def _llm(store, sec, messages, max_tokens=1400):
    ep, key = sec.get("aoai_endpoint") or os.getenv("AOAI_ENDPOINT"), sec.get("aoai_key") or os.getenv("AOAI_KEY")
    if not (ep and key):
        raise RuntimeError("AOAI not configured")
    import llm_chat
    return llm_chat.chat(ep, key, sec.get("aoai_deployment") or os.getenv("AOAI_DEPLOYMENT", "gpt-4o-mini"),
                         messages, max_tokens=max_tokens)


def _recent_titles(state, track, n=40):
    return [u["q"] for u in state.get("used", []) if u.get("track") == track][-n:]


def _paper_candidates(store, state):
    """Recent real papers not yet used: [{title, url, snippet, source}]."""
    seen = set(state.get("papers_seen", []))
    out = []
    try:
        import filler
        for p in filler.fetch_papers(limit=20):
            if p["url"] not in seen:
                out.append(p)
    except Exception as e:
        log.info("hf papers failed: %s", e)
    if len(out) < 5:
        try:
            import requests
            import filler
            r = requests.get("http://export.arxiv.org/api/query?search_query=cat:cs.AI+OR+cat:cs.LG+OR+cat:cs.CL"
                             "&sortBy=submittedDate&sortOrder=descending&max_results=30", timeout=15)
            for x in filler.parse_feed(r.content):
                url = x["url"].replace("http://", "https://")
                if url not in seen:
                    out.append({"title": x["title"], "url": url, "snippet": x["snippet"], "source": "arXiv"})
        except Exception as e:
            log.info("arxiv failed: %s", e)
    return out


def pick_topic(track, state, pool_items=()):
    """Next topic from the bank: skip topics used in the last 30 posts of the
    track and anything already in today's pool; rotate by counter."""
    bank = TOPICS.get(track) or []
    if not bank:
        return None
    recent = {u.get("topic") for u in state.get("used", []) if u.get("track") == track}
    recent |= {it.get("topic") for it in pool_items}
    start = int((state.get("counters") or {}).get(track, 0))
    for k in range(len(bank)):
        t = bank[(start + k) % len(bank)]
        if t not in recent:
            return t
    return bank[start % len(bank)]


def pick_shape(state, track):
    n = int((state.get("counters") or {}).get(track, 0))
    return HOOK_SHAPES[n % len(HOOK_SHAPES)]


def generate_one(store, track, sec=None, state=None, paper=None, topic=None, shape=None, avoid=()):
    """One LLM call → validated item (or None). Raises only if AOAI is not configured."""
    sec = sec if sec is not None else _cfg(store)
    state = state if state is not None else _load(store, STATE_BLOB, {"used": [], "papers_seen": []})
    style = str(sec.get("style_notes") or "").strip()
    recent = (_recent_titles(state, track) + [a for a in avoid if a])[-60:]
    topic = topic or (pick_topic(track, state) if track != "papers" else None)
    shape = shape or pick_shape(state, track)
    system = (
        "You write one LinkedIn post for software engineers: a question and its answer in the track "
        f"'{TRACK_NAMES[track]}'. Audience: engineers preparing for interviews and building real systems. "
        "Be correct, concrete and specific; no fluff, no marketing. " + HOOK_RULES + "\n\n"
        "Track guidance: " + GUIDE[track] + "\n\n"
        "Return ONLY a JSON object with these keys:\n"
        "hook (string <= 90 chars), question (string, self-contained, <= 400 chars), "
        "options (array of 0-4 short strings, only when a multiple-choice framing makes people comment), "
        "difficulty ('easy'|'medium'|'hard'), "
        "answer (string, <= 550 chars: first line 'Key idea: ...', then at most 3 numbered steps, each one "
        "line; no code inside answer), code (string, Python, <= 10 lines, or empty), "
        "complexity (string, e.g. 'Time O(n) · Space O(1)', or a key number for design topics), "
        "takeaway (one sentence), tags (2-3 CamelCase hashtags without #), "
        f"companies (array of 2-3 keys from {json.dumps(COMPANY_POOLS[track])} whose interview loops are known "
        "to ask this kind of question; be truthful — pick companies where this topic is commonly reported), "
        "level (string, the roles/levels this is typically asked for, e.g. 'SDE II / Senior' or "
        "'Staff / Principal' or 'all levels'), "
        "visual (object: one of " + json.dumps(VISUAL_KINDS) + " — schemas: "
        "{kind:'array', values:[numbers or short strings], highlight:[indices], pointers:{index:'label'}, caption:''} | "
        "{kind:'code', lang:'python', code:'<= 12 short lines'} | {kind:'boxes', items:['4-6 labels']} | "
        "{kind:'graph', nodes:['3-6 labels'], edges:[[from,to],...]} | {kind:'tree', values:[level-order, null for gaps]} | "
        "{kind:'metric', big:'headline number', small:'what it is', big2:'', small2:''} | "
        "{kind:'compare', left:{title:'', points:['<=4']}, right:{title:'', points:['<=4']}} | "
        "{kind:'table', header:['','A','B'], rows:[['row','x','y']]} | {kind:'none'}).\n"
        "The visual must illustrate THIS question (the example array, the flow, the loop, the number).\n"
        + f"Hook shape for this post: {shape}\n"
        + (f"AVOID — do not reuse these hooks/questions or their framing: {json.dumps(recent)}\n" if recent else "")
        + (f"Owner's style notes (follow them): {style}\n" if style else "")
        + "No markdown, no code fences, JSON only.")
    if track == "papers":
        if not paper:
            return None
        user = (f"Paper title: {paper['title']}\nURL: {paper['url']}\nSource: {paper.get('source', '')}\n"
                f"Abstract: {(paper.get('snippet') or '')[:1500]}\n\nWrite the post JSON. Set url to the paper URL.")
    else:
        seed = hashlib.sha1(f"{track}{topic}{_now().isoformat()}".encode()).hexdigest()[:6]
        user = (f"Topic for this post: {topic}.\nDifficulty: {['easy', 'medium', 'medium', 'hard'][int(seed, 16) % 4]}.\n"
                f"Write the post JSON now (variation seed {seed}).")
    out = _llm(store, sec, [{"role": "system", "content": system}, {"role": "user", "content": user}])
    item = validate(_parse_json(out), track)
    if item and track == "papers":
        item["url"] = paper["url"]
        item["source"] = paper.get("source") or "paper"
        item["topic"] = paper["title"][:80]
    elif item:
        item["source"] = "llm"
        item["topic"] = topic
    return item


