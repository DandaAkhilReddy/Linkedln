def post_one(store, track):
    """Post the next item for `track`: pool → generate on the fly → seed bank.
    Returns notes; '1 posted, …' on success (never raises)."""
    import linkedin_client
    p = pool(store)
    state = _load(store, STATE_BLOB, {"used": [], "papers_seen": []})
    item = None
    src = "pool"
    if p[track]:
        item = p[track].pop(0)
        allp = _load(store, POOL_BLOB, {})
        allp[track] = p[track]
        _save(store, POOL_BLOB, allp)
    else:
        src = "on-the-fly"
        try:
            sec = _cfg(store)
            paper = None
            if track == "papers":
                cands = _paper_candidates(store, state)
                paper = cands[0] if cands else None
                if paper:
                    state.setdefault("papers_seen", []).append(paper["url"])
            item = generate_one(store, track, sec, state, paper,
                                topic=pick_topic(track, state) if track != "papers" else None) if (track != "papers" or paper) else None
        except Exception as e:
            log.info("on-the-fly generation failed: %s", e)
            item = None
        if item is None:
            src = "seed"
            used = {u.get("id") for u in state.get("used", [])}
            fresh = [s for s in seed_items(track) if s["id"] not in used]
            if not fresh:
                return [f"edu {track}: nothing available (pool empty, LLM down, seeds used)"]
            item = fresh[0]
        item["number"] = _next_number(state, track)
        try:
            _render_and_store(store, item)
        except Exception as e:
            log.warning("render failed: %s", e)
            item["card_blob"] = ""
    png = None
    if item.get("card_blob"):
        try:
            png = store.download_blob(item["card_blob"]).readall()
        except Exception:
            png = None
    if png is None:
        try:
            import edu_cards
            png = edu_cards.render(track, item["question"], item.get("visual"), item.get("number"), item.get("difficulty"),
                                   companies=companies_for(item), logo_loader=_logo_loader())
        except Exception:
            png = None
    include_code = str(_cfg(store).get("edu_code", "false")).lower() == "true"
    text, mentions = caption_parts(item, include_code)
    title = f"{TRACK_NAMES[track]}: {item['hook'][:80]}"
    note = ""
    try:
        if png:
            urn = linkedin_client.post_with_image(text, png, title=title, mentions=mentions)
        else:
            urn = linkedin_client.post_text(text, mentions=mentions)
    except Exception as e:
        try:
            urn = linkedin_client.post_text(text, mentions=mentions)
            note = f" (text-only after: {str(e)[:80]})"
        except Exception as e2:
            # put it back so the content isn't lost
            if src == "pool":
                allp = _load(store, POOL_BLOB, {})
                allp[track] = [item] + list(allp.get(track, []))
                _save(store, POOL_BLOB, allp)
            return [f"edu {track} failed: {str(e)[:100]} | text: {str(e2)[:80]}"]
    state.setdefault("used", []).append({"id": item["id"], "track": track, "q": item["question"][:90],
                                         "topic": item.get("topic"), "ts": _now().isoformat(), "urn": urn})
    state["used"] = state["used"][-600:]
    _save(store, STATE_BLOB, state)
    try:
        plog = _load(store, "li_post_log.json", [])
        plog.append({"ts": _now().isoformat(), "company": "edu", "variant": track, "urn": urn,
                     "title": item["hook"][:120], "source": src})
        _save(store, "li_post_log.json", plog[-2000:])
    except Exception:
        pass
    return [f"posted edu {track} #{item.get('number')} ({src}): {item['hook'][:60]} {urn}{note}",
            f"1 posted, {len(pool(store)[track])} {track} left"]


