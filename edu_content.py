def plan_text(store):
    """Today's queued questions per track (for the morning email)."""
    p = pool(store)
    tg = targets(store)
    lines = []
    for t in TRACKS:
        items = p[t]
        lines.append(f"{TRACK_NAMES[t]} ({len(items)} ready of {tg[t]} planned):")
        for it in items[:tg[t]]:
            lines.append(f"  • {it['hook']}")
        if not items:
            lines.append("  (generated on the fly at post time)")
    return "\n".join(lines)


def posted_text(store, hours=24):
    """What went out in the last `hours`, grouped, with links."""
    plog = _load(store, "li_post_log.json", [])
    cutoff = (_now() - timedelta(hours=hours)).isoformat()
    recent = [p for p in plog if p.get("ts", "") >= cutoff]
    by = {}
    for p in recent:
        by.setdefault(p.get("variant"), []).append(p)
    jobs = sum(len(v) for k, v in by.items() if k and k.endswith("_hook"))
    lines = [f"Posted in the last {hours}h: {len(recent)} total — {jobs} job cards, "
             + ", ".join(f"{len(by.get(t, []))} {TRACK_NAMES[t]}" for t in TRACKS)
             + f", {len(by.get('poll', []))} poll, {len(by.get('carousel', []))} carousels, "
             f"{sum(len(by.get(k, [])) for k in ('news', 'hn', 'paper', 'chart'))} news/charts"]
    for t in TRACKS:
        for p in by.get(t, [])[:10]:
            urn = p.get("urn") or ""
            link = f"https://www.linkedin.com/feed/update/{urn}/" if urn.startswith("urn:") else ""
            lines.append(f"  [{TRACK_NAMES[t]}] {p.get('title', '')[:70]}  {link}")
    return "\n".join(lines)
