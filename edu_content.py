# ---------- storage helpers ----------

def _load(store, name, default):
    try:
        return json.loads(store.download_blob(name).readall())
    except Exception:
        return default


def _save(store, name, obj):
    store.upload_blob(name, json.dumps(obj), overwrite=True)


def _now():
    return datetime.datetime.now(timezone.utc)


def _cfg(store):
    try:
        import linkedin_client
        return linkedin_client._blob_secrets()
    except Exception:
        return {}


def targets(store, sec=None):
    """{track: posts per day} from li_secrets (edu_dsa, edu_sd, …), 0 if disabled."""
    sec = sec if sec is not None else _cfg(store)
    if str(sec.get("edu_enabled", "true")).lower() != "true":
        return {t: 0 for t in TRACKS}
    out = {}
    for t in TRACKS:
        try:
            out[t] = max(0, min(20, int(sec.get(f"edu_{t}", DEFAULT_PER_TRACK))))
        except Exception:
            out[t] = DEFAULT_PER_TRACK
    return out


